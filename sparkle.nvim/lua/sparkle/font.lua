-- glyph rows as strings of '#' and '.'
function M.glyph(ch)
  return G[ch:upper()]
end

-- Build a boolean mask for a word. Returns {w, h, scale, adv, at(x, y)}.
function M.mask(word, scale, adv)
  scale = scale or 1
  adv = adv or 6 * scale
  local n = #word
  local w = adv * (n - 1) + M.W * scale
  local h = M.H * scale
  local m = {}
  for i = 1, n do
    local g = M.glyph(word:sub(i, i))
    if g then
      local ox = (i - 1) * adv
      for gy = 1, M.H do
        local r = g[gy]
        for gx = 1, M.W do
          if r:sub(gx, gx) == "#" then
            for sy = 0, scale - 1 do
              for sx = 0, scale - 1 do
                m[((gy - 1) * scale + sy) * w + ox + (gx - 1) * scale + sx] = true
              end
            end
          end
        end
      end
    end
  end
  return {
    w = w, h = h, scale = scale, adv = adv, n = n,
    at = function(x, y)
      return x >= 0 and y >= 0 and x < w and y < h and m[y * w + x] == true
    end,
  }
end

return M
